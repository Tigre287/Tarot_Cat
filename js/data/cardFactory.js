// สร้างคำอ่านครบทุกหมวดจากความหมายมาตรฐานของไพ่

function keywordText(keywords) {
  return keywords.join(' · ');
}

export function makeCard({ id, th, en, arcana, suit, num, up, rev }) {
  const upright = keywordText(up);
  const reversed = keywordText(rev);

  return {
    id,
    th,
    en,
    arcana,
    suit,
    num,
    up,
    rev,
    cat: {
      work: {
        up: `เรื่องงาน ไพ่${th}หยิบประเด็น${upright}มาวางตรงหน้า ลองดูว่าเกิดกับเนื้องาน คน หรือทิศทางของเรา แล้วค่อยเลือกว่าจะขยับตรงไหนก่อน`,
        rev: `ไพ่${th}กลับหัวในเรื่องงานชี้ไปที่${reversed} แม่หมอแมวอ้วนขอให้พักความรีบไว้ก่อน เช็กแผนกับรายละเอียดให้ครบแล้วค่อยเดินต่อ`
      },
      money: {
        up: `พอถามเรื่องเงิน ไพ่${th}พูดถึง${upright}แบบชัด ๆ ตัวเลขจริงสำคัญกว่าความรู้สึกว่า “น่าจะไหว” เปิดบัญชีดูแล้ววางแผนตามกำลังนะ`,
        rev: `ไพ่${th}กลับหัวมาแตะเรื่อง${reversed} กระเป๋าสตางค์ไม่ชอบความชะล่าใจจ้า เช็กรายรับรายจ่ายและอย่ารับความเสี่ยงที่ยังไม่เข้าใจ`
      },
      health: {
        up: `เรื่องสุขภาพ ไพ่${th}โยงกับ${upright} ลองฟังทั้งกายและใจแบบไม่ด่วนตัดสิน แล้วกลับมาจัดเวลานอน อาหาร และการพักให้สมดุล`,
        rev: `ไพ่${th}กลับหัวเตือนเรื่อง${reversed} ร่างกายไม่ใช่ลูกจ้างที่สั่งโอทีได้ทุกวัน พักให้พอ และพบแพทย์ถ้ามีอาการผิดปกติต่อเนื่อง`
      },
      love: {
        up: `เรื่องหัวใจ ไพ่${th}พาเราไปมอง${upright} คำหวานฟังได้ แต่อย่าลืมดูการกระทำ แล้วบอกความต้องการของตัวเองให้ชัดด้วย`,
        rev: `ไพ่${th}กลับหัวในเรื่องรักสะกิดถึง${reversed} อย่าเพิ่งเขียนบทจบในหัวคนเดียว คุยขอบเขตและความต้องการกันก่อนตัดสินใจนะ`
      }
    }
  };
}
