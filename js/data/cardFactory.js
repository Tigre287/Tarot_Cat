// สร้างคำอ่านครบทุกหมวดจากความหมายมาตรฐานของไพ่

function keywordText(keywords) {
  return keywords.join(' · ');
}

export function makeCard({ id, th, en, arcana, suit, num, up, rev }) {
  const upright = keywordText(up);
  const reversed = keywordText(rev);

  return {
    id,
    th,
    en,
    arcana,
    suit,
    num,
    up,
    rev,
    cat: {
      work: {
        up: `ด้านการงาน ไพ่${th}สะท้อนเรื่อง${upright} ดูว่าสิ่งนี้กำลังเกิดตรงไหน แล้วเลือกวิธีตอบสนองที่รอบคอบที่สุด`,
        rev: `ด้านการงาน ไพ่${th}กลับหัวสะท้อนเรื่อง${reversed} ทบทวนแผน ตรวจรายละเอียด และแก้จุดติดขัดก่อนเดินต่อ`
      },
      money: {
        up: `ด้านการเงิน ไพ่${th}ชี้ถึง${upright} กลับมาดูตัวเลขจริง วางแผนตามกำลัง และตัดสินใจโดยไม่ใช้อารมณ์`,
        rev: `ด้านการเงิน ไพ่${th}กลับหัวสะท้อน${reversed} ตรวจรายรับรายจ่ายและอย่ารับความเสี่ยงที่ยังไม่เข้าใจ`
      },
      health: {
        up: `ด้านสุขภาพ ไพ่${th}เชื่อมโยงกับ${upright} สังเกตทั้งกายและใจ พร้อมรักษาสมดุลการนอน อาหาร และการพักผ่อน`,
        rev: `ด้านสุขภาพ ไพ่${th}กลับหัวเตือนเรื่อง${reversed} อย่าฝืนร่างกาย พักให้พอ และพบแพทย์หากมีอาการผิดปกติต่อเนื่อง`
      },
      love: {
        up: `ด้านความรัก ไพ่${th}นำประเด็น${upright}ขึ้นมา ดูทั้งคำพูดและการกระทำ แล้วสื่อสารความต้องการอย่างจริงใจ`,
        rev: `ด้านความรัก ไพ่${th}กลับหัวชี้ถึง${reversed} อย่ารีบสรุปจากอารมณ์ คุยขอบเขตและความต้องการก่อนตัดสินใจ`
      }
    }
  };
}
